export function formatDateHeader(lang: Lang, d: Date): string {
  if (lang === "zh") {
    return `${d.getMonth() + 1}月${d.getDate()}日 · 星期${WEEKDAYS.zh[d.getDay()]}`;
  }
  const locale = lang === "es" ? "es-ES" : "en-US";
  return d.toLocaleDateString(locale, { month: "short", day: "numeric", weekday: "long" });
}

export function greetingForHour(lang: Lang, h: number): string {
  if (lang === "es") {
    if (h < 5) return "Buenas noches, explorador.";
    if (h < 12) return "Buenos días, explorador.";
    if (h < 19) return "Buenas tardes, explorador.";
    return "Buenas noches, explorador.";
  }
  if (lang === "en") {
    if (h < 5) return "Late night, Explorer.";
    if (h < 12) return "Good morning, Explorer.";
    if (h < 18) return "Good afternoon, Explorer.";
    return "Good evening, Explorer.";
  }
  if (h < 5) return "夜深了，探索者。";
  if (h < 11) return "早上好，探索者。";
  if (h < 14) return "中午好，探索者。";
  if (h < 18) return "下午好，探索者。";
  return "晚上好，探索者。";
}

